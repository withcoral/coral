import { dirname, join } from 'node:path'

import type { Database } from './database'
import { writeAtomic } from './desktop-file'
import { LOOPBACK, type Ports } from './ports'
import { spawnLauncher, type Launcher, type SpawnOptions } from './process'

/**
 * The runtime registers this fixed Provider OAuth callback when `CORAL_DESKTOP=1`
 * leaves `[listeners.auth]` unset, so provider OAuth clients can register it once.
 */
export const DESKTOP_OAUTH_CALLBACK_URL = 'http://127.0.0.1:8779/provider-oauth/callback'

export function loopbackUrl(port: number): string {
  return `http://${LOOPBACK}:${port}`
}

/** The variable that gives the runtime its Postgres URL, which `config.toml` never holds. */
const DATABASE_URL_ENV = 'CORAL_DESKTOP_DATABASE_URL'

/**
 * Writes the runtime's `config.toml` from scratch. Desktop owns the file and
 * regenerates it on every launch, so a schema change never strands a user with
 * a file the runtime refuses.
 */
export async function writeRuntimeConfig(
  stateDir: string,
  ports: Ports,
  database: Database,
): Promise<void> {
  const databaseSection =
    database.backend === 'postgres'
      ? `
[database]
backend = "postgres"
url_env = "${DATABASE_URL_ENV}"
`
      : ''
  await writeAtomic(
    join(stateDir, 'config.toml'),
    `# Generated by Coral Desktop; edits are overwritten.

[listeners.grpc]
bind = "${LOOPBACK}:${ports.grpc}"

[listeners.mcp]
bind = "${LOOPBACK}:${ports.mcp}"

# Desktop stops the runtime within its stop timeout: Runs still live are
# interrupted at once instead of draining.
[runtime]
shutdown_drain_seconds = 0
${databaseSection}`,
    // The runtime treats any file beside config.toml in a fresh state
    // directory as foreign state, so a crash must not leave one there.
    dirname(stateDir),
  )
}

/** The runtime exits with this code when another runtime holds its state directory. */
export const STATE_LOCKED_EXIT_CODE = 75

/**
 * Launches the runtime binary. Desktop stops it by closing its stdin: the one
 * graceful stop on every platform, and one that the OS performs too when
 * Desktop dies, so the runtime never outlives Desktop. The launcher also tells
 * the runtime to watch its stdin. Without the pipe, the runtime would read an
 * empty stdin and stop at once.
 */
export function runtimeLauncher(command: string, options: Omit<SpawnOptions, 'stopBy'>): Launcher {
  const launch = spawnLauncher(command, { ...options, stopBy: 'stdin' })
  return (env) => launch({ ...env, CORAL_STOP_ON_STDIN_CLOSE: '1' })
}

/** The variables that make a runtime launch Desktop's. */
export function runtimeEnv(
  stateDir: string,
  ports: Ports,
  database: Database,
): Record<string, string> {
  return {
    CORAL_CONFIG_DIR: stateDir,
    CORAL_DESKTOP: '1',
    CORAL_LOCAL_WEB_URL: loopbackUrl(ports.reef),
    ...(database.backend === 'postgres' ? { [DATABASE_URL_ENV]: database.url } : {}),
  }
}

export type ReefEnv = {
  HOST: string
  PORT: string
  CORAL_ENDPOINT: string
  CORAL_WEB_AUTH_MODE: 'disabled'
  CORAL_UPSTREAM_OAUTH_CALLBACK_URL: string
}

/** The variables that point Reef at this launch's runtime, in local mode. */
export function reefEnv(ports: Ports): ReefEnv {
  return {
    HOST: LOOPBACK,
    PORT: String(ports.reef),
    CORAL_ENDPOINT: loopbackUrl(ports.grpc),
    CORAL_WEB_AUTH_MODE: 'disabled',
    CORAL_UPSTREAM_OAUTH_CALLBACK_URL: DESKTOP_OAUTH_CALLBACK_URL,
  }
}

/** Adds loopback to NO_PROXY, so a system proxy never intercepts Desktop's own traffic. */
export function withLoopbackProxyBypass(env: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const result = { ...env }
  for (const key of ['NO_PROXY', 'no_proxy']) {
    const hosts =
      result[key]
        ?.split(',')
        .map((host) => host.trim())
        .filter(Boolean) ?? []
    for (const host of [LOOPBACK, 'localhost', '::1']) {
      if (!hosts.some((existing) => existing.toLowerCase() === host)) hosts.push(host)
    }
    result[key] = hosts.join(',')
  }
  return result
}
