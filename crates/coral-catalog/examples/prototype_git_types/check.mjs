// PROTOTYPE of `npx @withcoral/check`: generate coral.shared from functions/**, then run tsc.
import { readdirSync, mkdirSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { execFileSync } from "node:child_process";

const root = process.cwd();
const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : path.endsWith(".ts") ? [path] : [];
});
const tree = {};
for (const file of walk(join(root, "functions"))) {
  const segments = relative(join(root, "functions"), file).replace(/\.ts$/, "").split(sep);
  let node = tree;
  for (const s of segments.slice(0, -1)) node = node[s] ??= {};
  node[segments.at(-1)] = `typeof import("../functions/${segments.join("/")}").default`;
}
const render = (node, pad) => typeof node === "string" ? node :
  "{\n" + Object.entries(node).map(([k, v]) => `${pad}  readonly ${JSON.stringify(k)}: ${render(v, pad + "  ")};\n`).join("") + pad + "}";
mkdirSync(join(root, ".coral-check"), { recursive: true });
writeFileSync(join(root, ".coral-check/shared.gen.d.ts"),
  `// Generated by the checker from functions/**. Do not edit.\ndeclare namespace coral {\n  interface Shared ${render(tree, "  ")}\n}\n`);
try {
  execFileSync("npx", ["-y", "-p", "typescript@6.0.3", "tsc", "-p", ".", ...process.argv.slice(2)], { stdio: "inherit" });
} catch { process.exitCode = 1; }
